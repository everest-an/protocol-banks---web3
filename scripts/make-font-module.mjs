// One-off: embed the repo's Aeonik-Bold OTF as a base64 TS module so the
// serverless GIF renderer can register the brand font with zero filesystem
// dependencies (fonts under components/ are not traced into the function).
import fs from "node:fs"

const src = "E:/Protocol Bank/components/ui/textui/Aeonik-font-download/Aeonik-font-download/Aeonik-Bold.otf"
const out = "E:/Protocol Bank/lib/media/aeonik-bold.ts"

const b64 = fs.readFileSync(src).toString("base64")
const content = `// Generated by scripts/make-font-module.mjs — DO NOT EDIT BY HAND.
// Aeonik Bold (the site's brand font), embedded so the media renderer has no
// filesystem dependency at runtime.
export const AEONIK_BOLD_B64 = "${b64}"
`
fs.writeFileSync(out, content, "utf8")
console.log("wrote", out, "base64 chars:", b64.length)
